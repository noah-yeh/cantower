import { chromium } from 'playwright-core';
const URL = process.env.PROBE_URL || 'http://127.0.0.1:4182/';
const ok = (c, m) => console.log(c ? 'OK ' : 'ERR', m);
const browser = await chromium.launch({ channel: 'msedge', args: ['--mute-audio'] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 640 }, deviceScaleFactor: 2 })).newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.goto(URL, { waitUntil: 'networkidle' });
await page.waitForTimeout(300);
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(350);
await page.evaluate(async () => {
  const meta = await import('/src/core/meta.js');
  const roster = await import('/src/core/roster.js');
  const save = await import('/src/core/save.js');
  const runMod = await import('/src/core/run.js');
  const m = meta.createMeta(20261110);
  const ch = roster.createCharacter({ classId: 'warrior', raceId: 'stone', seed: 5 });
  ch.status = 'exploring'; ch.lives = 3; m.roster = [ch]; save.saveMeta(m);
  const run = runMod.createRun({ character: ch, seed: 42 });
  run.phase = 'shop';
  run.gold = 500;
  run.deck = ['guard', 'guard+1', 'brace+3'];
  const ids = ['guard', 'brace', 'heavy', 'w_ironWall', 'm_shield', 't_shell'];
  run.shop = { kind: 'card', refreshes: 0, relics: [], cards: ids.map((id) => ({ id, price: 100, sold: false })) };
  save.saveRun(run);
  m.run = { characterId: ch.id, floor: run.floor, paused: true };
  save.saveMeta(m);
});
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(400);
await page.locator('[data-action="resume"]').first().click();
await page.waitForTimeout(500);
const st = await page.evaluate(() => {
  const list = document.querySelector('.reward-list');
  const lr = list.getBoundingClientRect();
  const rows = [...list.querySelectorAll('.reward')];
  const overflow = rows.some((r) => r.getBoundingClientRect().bottom > lr.bottom + 1);
  const bodyScroll = document.querySelector('.overlay.shop-fixed').scrollHeight > innerHeight + 1;
  return { rows: rows.length, overflow, bodyScroll, pageErr: false };
});
ok(st.rows === 6, `6 格货（实际 ${st.rows}）`);
ok(!st.overflow && !st.bodyScroll, `矮屏一屏放下、无滚动（行溢出 ${st.overflow} / 页溢出 ${st.bodyScroll}）`);
await page.screenshot({ path: 'tools/probe/shot-v370-dense.png' });
await browser.close();
console.log('ALL PASS');
