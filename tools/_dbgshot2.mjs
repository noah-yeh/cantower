import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'msedge', args: ['--mute-audio'] });
const page = await (await browser.newContext({ viewport: { width: 540, height: 960 }, deviceScaleFactor: 2 })).newPage();
page.on('pageerror', e => console.log('[pageerror]', e.message));
await page.goto('http://127.0.0.1:4182/', { waitUntil: 'networkidle' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(300);
await page.evaluate(async () => {
  const meta = await import('/src/core/meta.js');
  const roster = await import('/src/core/roster.js');
  const runMod = await import('/src/core/run.js');
  const dungeon = await import('/src/core/dungeon.js');
  const save = await import('/src/core/save.js');
  const m = meta.createMeta(20261116);
  const a = roster.createCharacter({ classId: 'warrior', raceId: 'stone', seed: 11 });
  a.veteran = true;
  m.roster = [a];
  a.status = 'exploring';
  const run = runMod.createRun({ character: a, seed: 777 });
  run.floor = 3;
  dungeon.makeFloorMap(run);
  save.saveRun(run);
  m.run = { characterId: a.id, floor: run.floor };
  save.saveMeta(m);
});
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(700);
console.log('screen:', await page.evaluate(() => document.body.dataset.screen));
console.log('actions:', await page.evaluate(() => [...document.querySelectorAll('[data-action]')].map(e => e.dataset.action).slice(0, 40).join(',')));
console.log('guide visible:', await page.evaluate(() => !!document.querySelector('.maze-guide, [class*="guide"]')));
await browser.close();
