import { chromium } from 'playwright-core';
const URL = 'http://127.0.0.1:4182/';
const browser = await chromium.launch({ channel: 'msedge', args: ['--mute-audio'] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 760 }, deviceScaleFactor: 2 })).newPage();
await page.goto(URL, { waitUntil: 'networkidle' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(300);
await page.evaluate(async () => {
  const meta = await import('/src/core/meta.js');
  const roster = await import('/src/core/roster.js');
  const save = await import('/src/core/save.js');
  const eq = await import('/src/core/equipment.js');
  const m = meta.createMeta(20261110);
  const a = roster.createCharacter({ classId: 'warrior', raceId: 'stone', seed: 3 });
  a.status = 'idle'; a.veteran = true; a.arenaLeft = 3; a.relics = ['anvil', 'poisonGem'];
  a.relicSlots = ['whetstone'];
  const b = roster.createCharacter({ classId: 'mage', raceId: 'ember', seed: 4 });
  b.status = 'idle';
  m.roster = [a, b];
  save.saveMeta(m);
});
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(400);
await page.locator('[data-action="open-expedition"]').first().click();
await page.waitForTimeout(350);
await page.locator('[data-action="open-char"]').first().click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'tools/probe/now-hero-char.png' });
await page.locator('.hp-tab').first().click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'tools/probe/now-hero-gear.png' });
await page.locator('.hp-tab').last().click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'tools/probe/now-hero-relic.png' });
await browser.close();
console.log('done');
